class BuildError(Exception):
    """A problem with a post that the author needs to fix."""


# --------------------------------------------------------------- front matter

def parse_front_matter(text: str, path: Path) -> tuple[dict, str]:
    """Split a leading `---` block of `key: value` lines off the body."""
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        raise BuildError(f"{path.name}: needs a '---' front matter block at the top")

    # The closing fence is the first bare '---' after the opening one. Scanning
    # line by line rather than splitting on the string keeps a '---' further
    # down the post — inside a code block, say — from truncating the body.
    closing = next((i for i, line in enumerate(lines[1:], start=1)
                    if line.strip() == "---"), None)
    if closing is None:
        raise BuildError(f"{path.name}: front matter block is never closed with '---'")

    meta: dict[str, str | list[str]] = {}
    key = None
    for lineno, line in enumerate(lines[1:closing], start=2):
        if not line.strip():
            continue

        # An indented "- item" continues the list started by the previous key.
        item = re.match(r"\s+-\s+(.*)$", line)
        if item:
            if key is None or not isinstance(meta.get(key), list):
                raise BuildError(
                    f"{path.name} line {lineno}: a '- item' line has to sit under a "
                    f"key with nothing after its colon, like 'meta:'"
                )
            meta[key].append(_unquote(item.group(1)))
            continue

        if ":" not in line:
            raise BuildError(f"{path.name} line {lineno}: expected 'key: value', got {line!r}")
        key, value = line.split(":", 1)
        key = key.strip().lower()
        value = value.strip()
        meta[key] = _unquote(value) if value else []
    return meta, "\n".join(lines[closing + 1:]).lstrip("\n")


def _unquote(value: str) -> str:
    return value.strip().strip('"').strip("'")


# ----------------------------------------------------------------------- math
# Markdown and LaTeX fight over the same punctuation: `_` becomes emphasis, `*`
# becomes bold, `\\` gets eaten. So every math span is lifted out before the
# Markdown pass and put back afterwards, untouched. Code spans are matched too,
# but left in place — math inside a code block should stay visible as source.

_ALTERNATIVES = [
    ("code", r"```[\s\S]*?```"),
    ("code", r"`+[^`\n]+?`+"),
    ("escaped", r"\\\$"),
    ("display", r"\$\$[\s\S]+?\$\$"),
    ("display", r"\\\[[\s\S]+?\\\]"),
    ("display", r"\\begin\{(?P<env>[a-zA-Z]+\*?)\}[\s\S]+?\\end\{(?P=env)\}"),
    ("inline", r"\\\([\s\S]+?\\\)"),
    ("inline", r"\$(?!\s)(?:\\\$|[^$\n])+?(?<!\s)\$"),
]

_NAMES = [f"{kind}{i}" for i, (kind, _) in enumerate(_ALTERNATIVES)]
_SCANNER = re.compile(
    "|".join(f"(?P<{name}>{pat})" for name, (_, pat) in zip(_NAMES, _ALTERNATIVES))
)


def _token(index: int) -> str:
    # Letters and digits only: anything with an underscore or asterisk would
    # itself be reinterpreted by Markdown.
    return f"MATHSTASH{index}ENDSTASH"


def protect_math(text: str) -> tuple[str, list[tuple[str, str]]]:
    stash: list[tuple[str, str]] = []

    def replace(match: re.Match) -> str:
        for name in _NAMES:
            if match.group(name) is None:
                continue
            kind = name.rstrip("0123456789")
            if kind == "code":
                return match.group(0)  # leave code for Markdown to handle
            stash.append((kind, match.group(0)))
            return _token(len(stash) - 1)
        return match.group(0)

    return _SCANNER.sub(replace, text), stash


def restore_math(rendered: str, stash: list[tuple[str, str]]) -> str:
    """Put the math back, HTML-escaped.

    Escaping matters: `$a < b$` has to reach the browser as `&lt;`, or the parser
    treats it as the start of a tag. MathJax reads text content, so it sees `<`.
    """
    for index, (kind, raw) in enumerate(stash):
        token = _token(index)
        if kind == "escaped":
            # Keep the backslash: MathJax's processEscapes is what turns `\$`
            # into a literal dollar at display time. Emitting a bare `$` here
            # would open an inline math span in the browser instead.
            rendered = rendered.replace(token, r"\$")
            continue

        escaped = html.escape(raw, quote=False)
        if kind == "display":
            # A display equation alone in a paragraph becomes a block that can
            # scroll sideways on a narrow screen; <div> cannot live inside <p>.
            body = textwrap.indent(escaped.strip(), "  ")
            block = f'<div class="math-block">\n{body}\n</div>'
            rendered = re.sub(
                rf"<p>\s*{token}\s*</p>", lambda _m, b=block: b, rendered
            )
        rendered = rendered.replace(token, escaped)
    return rendered


# ------------------------------------------------------------------ callouts
# A blockquote whose first line is bold becomes one of the site's callout boxes:
#
#     > **One thing to watch**
#     > A bare `$` opens inline math.
#
# The block is rendered on its own and held aside as raw HTML, so Markdown does
# not get a second look at it.

CALLOUT_RE = re.compile(
    r"(?m)^> \*\*(?P<title>[^*\n]+)\*\*[ \t]*\n(?P<rest>(?:^>.*\n?)*)"
)


def extract_callouts(text: str) -> tuple[str, list[str]]:
    blocks: list[str] = []

    def replace(match: re.Match) -> str:
        rest = "\n".join(
            re.sub(r"^>[ \t]?", "", line) for line in match.group("rest").splitlines()
        )
        inner = render_markdown(rest) if rest.strip() else ""
        blocks.append(
            '<div class="callout">\n'
            f'  <p class="callout-title">{render_inline(match.group("title"))}</p>\n'
            f"{textwrap.indent(inner, '  ')}\n</div>"
        )
        return f"\nCALLOUTSTASH{len(blocks) - 1}ENDSTASH\n"

    return CALLOUT_RE.sub(replace, text), blocks


def restore_callouts(rendered: str, blocks: list[str]) -> str:
    for index, block in enumerate(blocks):
        token = f"CALLOUTSTASH{index}ENDSTASH"
        rendered = re.sub(rf"<p>\s*{token}\s*</p>", lambda _m, b=block: b, rendered)
        rendered = rendered.replace(token, block)
    return rendered


def render_markdown(body: str) -> str:
    body, callouts = extract_callouts(body)
    protected, stash = protect_math(body)
    rendered = str(markdown2.markdown(protected, extras=MARKDOWN_EXTRAS))
    rendered = restore_math(rendered, stash)
    return restore_callouts(rendered, callouts).strip()


def render_inline(text: str) -> str:
    """Render a one-line field (title, summary) — math allowed, no paragraph tags."""
    protected, stash = protect_math(text)
    rendered = str(markdown2.markdown(protected, extras=["smarty-pants"])).strip()
    if rendered.startswith("<p>") and rendered.endswith("</p>"):
        rendered = rendered[3:-4]
    return restore_math(rendered, stash)


def plain_text(text: str) -> str:
    """A version fit for <title> and <meta>: no tags, no math delimiters."""
    stripped = re.sub(r"\$\$?|\\[()\[\]]", "", text)
    stripped = re.sub(r"[*_`]", "", stripped)
    return html.escape(" ".join(stripped.split()), quote=True)


# ---------------------------------------------------------------------- posts

class Post:
    def __init__(self, path: Path):
        self.path = path
        self.slug = path.stem
        meta, body = parse_front_matter(path.read_text(encoding="utf-8"), path)

        if "title" not in meta:
            raise BuildError(f"{path.name}: front matter needs a 'title:'")
        self.title = meta["title"]
        self.summary = meta.get("summary", "")
        self.draft = meta.get("draft", "").lower() in {"true", "yes", "1"}
        self.date = self._parse_date(meta.get("date"), path)
        self.body = body
        self.body_html = render_markdown(body)
        self.minutes = self._reading_time(meta.get("reading_time"), body)

    @staticmethod
    def _parse_date(value: str | None, path: Path) -> dt.date:
        if not value:
            match = re.match(r"(\d{4}-\d{2}-\d{2})", path.stem)
            if not match:
                raise BuildError(
                    f"{path.name}: needs a 'date: YYYY-MM-DD', or a date at the "
                    f"start of the filename"
                )
            value = match.group(1)
        try:
            return dt.date.fromisoformat(value)
        except ValueError as exc:
            raise BuildError(f"{path.name}: bad date {value!r} — use YYYY-MM-DD") from exc

    @staticmethod
    def _reading_time(override: str | None, body: str) -> int:
        if override:
            return int(re.sub(r"\D", "", override) or 1)
        words = len(body.split())
        return max(1, round(words / WORDS_PER_MINUTE))

    @property
    def date_iso(self) -> str:
        return self.date.isoformat()

    @property
    def date_human(self) -> str:
        return f"{self.date.day} {self.date:%B %Y}"

    @property
    def out_path(self) -> Path:
        return OUT_DIR / f"{self.slug}.html"


