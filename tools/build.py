def update_index(posts: list[Post]) -> bool:
    """Rewrite the post list in blog.html, leaving the rest of the page alone."""
    text = INDEX.read_text(encoding="utf-8")
    start = text.find(LIST_START)
    end = text.find(LIST_END)
    if start == -1 or end == -1:
        raise BuildError(
            f"blog.html is missing the {LIST_START}…{LIST_END} markers that say "
            f"where the post list goes"
        )

    head = text[: text.index("\n", start) + 1]
    entries = "\n\n".join(render_entry(p) for p in posts) or "    <p>No posts yet.</p>"
    updated = head + "\n" + entries + "\n\n" + text[end:]
    if updated == text:
        return False
    INDEX.write_text(updated, encoding="utf-8")
    return True


def sweep_orphans(directory: Path, live: set[Path]) -> list[Path]:
    """Delete generated pages whose Markdown source is gone. Hand-written pages
    carry no generated marker, so they are never touched."""
    removed = []
    for page in sorted(directory.glob("*.html")):
        if page in live:
            continue
        if GENERATED_BY in page.read_text(encoding="utf-8"):
            page.unlink()
            removed.append(page)
    return removed


def write_if_changed(path: Path, text: str, say) -> bool:
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return False
    path.write_text(text, encoding="utf-8")
    say(f"  wrote  {path.relative_to(ROOT)}")
    return True


def build(quiet: bool = False) -> int:
    def say(message: str) -> None:
        if not quiet:
            print(message)

    if not POSTS_DIR.is_dir():
        raise BuildError(f"no posts directory at {POSTS_DIR.relative_to(ROOT)}")

    written = 0
    drafts: list[str] = []

    # ---- blog posts ------------------------------------------------------
    posts, post_drafts = [], []
    for path in sorted(POSTS_DIR.glob("*.md")):
        if path.name.startswith("_"):
            continue  # _template.md and friends
        post = Post(path)
        (post_drafts if post.draft else posts).append(post)
    posts.sort(key=lambda p: (p.date, p.slug), reverse=True)
    drafts += [f"blog/posts/{p.path.name}" for p in post_drafts]

    for post in posts:
        written += write_if_changed(post.out_path, render_page(post), say)
    for page in sweep_orphans(OUT_DIR, {p.out_path for p in posts}):
        say(f"  removed {page.relative_to(ROOT)} (no longer published)")
    if update_index(posts):
        say("  wrote  blog.html (post list)")

    # ---- course notes ----------------------------------------------------
    notes, note_drafts = [], []
    for path in sorted(NOTES_DIR.glob("*.md")) if NOTES_DIR.is_dir() else []:
        if path.name.startswith("_"):
            continue
        note = Note(path)
        (note_drafts if note.draft else notes).append(note)
    drafts += [f"notes/{n.path.name}" for n in note_drafts]

    for note in notes:
        written += write_if_changed(note.out_path, note.render(), say)
    for page in sweep_orphans(NOTES_DIR, {n.out_path for n in notes}):
        say(f"  removed {page.relative_to(ROOT)} (no longer published)")

    # ---- the three standing pages ---------------------------------------
    classes, class_drafts = load_entries(CLASSES_DIR, "class")
    research, research_drafts = load_entries(RESEARCH_DIR, "research")
    drafts += [f"content/classes/{e.path.name}" for e in class_drafts]
    drafts += [f"content/research/{e.path.name}" for e in research_drafts]

    home = read_page("index")
    written += write_if_changed(ROOT / "index.html", shell(
        depth=0, active="about",
        title=f"{site_config()['name']} — {plain_text(home.meta.get('tab_title', 'About'))}",
        description=plain_text(home.description),
        body=render_home(home), source="content/pages/index.md"), say)

    classes_page = read_page("classes")
    written += write_if_changed(ROOT / "classes.html", shell(
        depth=0, active="classes",
        title=f"{plain_text(classes_page.title)} — {site_config()['name']}",
        description=plain_text(classes_page.description),
        body=render_classes(classes_page, classes),
        source="content/pages/classes.md"), say)

    research_page = read_page("research")
    written += write_if_changed(ROOT / "research.html", shell(
        depth=0, active="research",
        title=f"{plain_text(research_page.title)} — {site_config()['name']}",
        description=plain_text(research_page.description),
        body=render_research(research_page, research),
        source="content/pages/research.md"), say)

    for draft in drafts:
        say(f"  draft  {draft} — not published "
            f"(remove 'draft: true' to publish it)")

    say(f"{len(posts)} post{'s' if len(posts) != 1 else ''}, {len(notes)} note page"
        f"{'s' if len(notes) != 1 else ''}, {len(classes)} class"
        f"{'es' if len(classes) != 1 else ''}, {len(research)} project"
        f"{'s' if len(research) != 1 else ''}; {written} file"
        f"{'s' if written != 1 else ''} rebuilt"
        + (f", {len(drafts)} held back as draft{'s' if len(drafts) != 1 else ''}" if drafts else ""))
    return len(posts)


