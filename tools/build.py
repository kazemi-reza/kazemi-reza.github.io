def serve(port: int) -> None:
    import functools
    import http.server
    import socketserver
    import threading
    import time

    def snapshot() -> dict:
        watched = [Path(__file__)]
        for folder in (POSTS_DIR, NOTES_DIR, PAGES_DIR, CLASSES_DIR, RESEARCH_DIR, CONTENT):
            if folder.is_dir():
                watched += list(folder.glob("*.md"))
        return {p: p.stat().st_mtime for p in watched if p.exists()}

    def watch() -> None:
        last = snapshot()
        while True:
            time.sleep(0.5)
            current = snapshot()
            if current == last:
                continue
            last = current
            print("\nchange detected — rebuilding")
            try:
                build()
            except BuildError as exc:
                print(f"  error: {exc}")

    threading.Thread(target=watch, daemon=True).start()

    handler = functools.partial(http.server.SimpleHTTPRequestHandler, directory=str(ROOT))
    socketserver.TCPServer.allow_reuse_address = True
    with socketserver.TCPServer(("127.0.0.1", port), handler) as httpd:
        print(f"\nserving http://127.0.0.1:{port}/blog.html — Ctrl-C to stop")
        print("editing a post rebuilds it; refresh the browser to see it\n")
        try:
            httpd.serve_forever()
        except KeyboardInterrupt:
            print("\nstopped")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--serve", action="store_true",
                        help="rebuild, then serve locally and rebuild on every save")
    parser.add_argument("--port", type=int, default=8000, help="port for --serve (default 8000)")
    args = parser.parse_args()

    try:
        build()
    except BuildError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    if args.serve:
        serve(args.port)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
