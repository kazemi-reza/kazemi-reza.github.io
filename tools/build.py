ENTRY = """    <article class="entry">
      <h3><a href="blog/{slug}.html">{title_html}</a></h3>
      <p class="meta"><time datetime="{date_iso}">{date_human}</time><span>&middot;</span><span>{minutes} min</span></p>
      <p>{summary_html}</p>
    </article>"""


def render_page(post: Post) -> str:
    body = (
        '    <a class="back" href="../blog.html">&larr; All posts</a>\n\n'
        f'    <h1 class="page-title">{render_inline(post.title)}</h1>\n'
        f'    <p class="meta"><time datetime="{post.date_iso}">{post.date_human}</time>'
        f'<span>&middot;</span><span>{post.minutes} min</span></p>\n\n'
        f"{post.body_html}"
    )
    return shell(
        depth=1,
        active="blog",
        title=f"{plain_text(post.title)} — {site_config()['name']}",
        description=plain_text(post.summary),
        body=body,
        source=f"blog/posts/{post.slug}.md",
    )


def render_entry(post: Post) -> str:
    return ENTRY.format(
        slug=post.slug,
        title_html=render_inline(post.title),
        date_iso=post.date_iso,
        date_human=post.date_human,
        minutes=post.minutes,
        summary_html=render_inline(post.summary) or "&nbsp;",
    )


# ----------------------------------------------------- classes & research --

ACTIVE_STATUSES = {"in progress", "ongoing", "active", "current"}
SEASONS = {"winter": 0, "spring": 1, "summer": 2, "fall": 3, "autumn": 3}

# Keys the templates use directly; anything else in the front matter is ignored
# rather than silently rendered somewhere unexpected.
ENTRY_KEYS = {"title", "course", "term", "status", "meta", "notes", "order", "draft"}


class Entry:
    """One course or one research project."""

    def __init__(self, path: Path, kind: str):
        self.path = path
        self.kind = kind
        meta, body = parse_front_matter(path.read_text(encoding="utf-8"), path)

        if "title" not in meta:
            raise BuildError(f"{path.name}: front matter needs a 'title:'")
        self.title = meta["title"]
        self.course = meta.get("course", "")
        self.term = meta.get("term", "")
        self.status = meta.get("status", "")
        self.spans = _as_list(meta.get("meta", []), path, "meta")
        self.notes = _as_list(meta.get("notes", []), path, "notes")
        self.draft = str(meta.get("draft", "")).lower() in {"true", "yes", "1"}
        self.order = int(meta.get("order", 100) or 100)
        self.body_html = render_markdown(body)

        if kind == "class" and not self.term:
            raise BuildError(f"{path.name}: a class needs a 'term:', e.g. 'Fall 2026'")

    @property
    def heading(self) -> str:
        if self.course:
            return f"{render_inline(self.course)} &middot; {render_inline(self.title)}"
        return render_inline(self.title)

    @property
    def term_key(self) -> tuple[int, int]:
        """Sorts 'Fall 2026' after 'Spring 2026'. Unparseable terms sort last."""
        match = re.search(r"(winter|spring|summer|fall|autumn)\s+(\d{4})", self.term, re.I)
        if not match:
            return (0, 0)
        return (int(match.group(2)), SEASONS[match.group(1).lower()])

    def render(self) -> str:
        bits = []
        if self.status:
            active = " tag--active" if self.status.lower() in ACTIVE_STATUSES else ""
            bits.append(f'<span class="tag{active}">{render_inline(self.status)}</span>')
        bits += [f"<span>{render_inline(span)}</span>" for span in self.spans]

        parts = [f'    <article class="entry">', f"      <h3>{self.heading}</h3>"]
        if bits:
            parts.append('      <p class="meta">' + "".join(bits) + "</p>")
        parts.append(textwrap.indent(self.body_html, "      "))
        if self.notes:
            items = "".join(
                f"        <li>{render_inline(note)}</li>\n" for note in self.notes
            )
            parts.append(f'      <ul class="note-links">\n{items}      </ul>')
        parts.append("    </article>")
        return "\n".join(parts)


def _as_list(value, path: Path, key: str) -> list[str]:
    if isinstance(value, list):
        return value
    if not value:
        return []
    raise BuildError(
        f"{path.name}: '{key}:' takes a list — put nothing after the colon and "
        f"write each item on its own indented '- ' line"
    )


def load_entries(directory: Path, kind: str) -> tuple[list[Entry], list[Entry]]:
    if not directory.is_dir():
        return [], []
    live, drafts = [], []
    for path in sorted(directory.glob("*.md")):
        if path.name.startswith("_"):
            continue
        entry = Entry(path, kind)
        (drafts if entry.draft else live).append(entry)
    return live, drafts


# ------------------------------------------------------------------- pages --

class PageSource:
    """content/pages/*.md — the title, the lede, and any closing prose."""

    def __init__(self, path: Path):
        self.path = path
        meta, body = parse_front_matter(path.read_text(encoding="utf-8"), path)
        if "title" not in meta:
            raise BuildError(f"{path.name}: front matter needs a 'title:'")
        self.meta = meta
        self.title = meta["title"]
        self.lede = meta.get("lede", "")
        self.description = meta.get("description", self.lede)
        self.body_html = render_markdown(body)


def read_page(name: str) -> PageSource:
    path = PAGES_DIR / f"{name}.md"
    if not path.exists():
        raise BuildError(f"missing {path.relative_to(ROOT)}")
    return PageSource(path)


def heading_block(page: PageSource) -> str:
    out = [f'    <h1 class="page-title">{render_inline(page.title)}</h1>']
    if page.lede:
        out.append(f'    <p class="lede">{render_inline(page.lede)}</p>')
    return "\n".join(out)


CARDS = [
    ("classes.html", "Classes &amp; Notes",
     "Coursework by term, with the typed notes I kept for each one."),
    ("research.html", "Research",
     "Projects I&rsquo;m working on, each with a short description of the problem."),
    ("blog.html", "Blog",
     "Longer write-ups, derivations, and things I wanted to explain to myself."),
]


def render_home(page: PageSource) -> str:
    role = page.meta.get("role", "")
    links = _as_list(page.meta.get("links", []), page.path, "links")

    parts = ['    <section class="hero">']
    if role:
        parts.append(f'      <p class="hero-role">{render_inline(role)}</p>')
    parts.append(f'      <h1 class="page-title">{render_inline(page.title)}</h1>')
    parts.append("    </section>\n")
    parts.append('    <div class="bio">')
    parts.append(textwrap.indent(page.body_html, "      "))
    if links:
        items = "".join(f"        <li>{render_inline(link)}</li>\n" for link in links)
        parts.append(f'\n      <ul class="links">\n{items}      </ul>')
    parts.append("    </div>\n")

    cards = "".join(
        f'      <li>\n        <a class="card" href="{href}">\n'
        f"          <h3>{name}</h3>\n          <p>{blurb}</p>\n"
        f"        </a>\n      </li>\n"
        for href, name, blurb in CARDS
    )
    parts.append("    <hr>\n")
    parts.append("    <h2>Elsewhere on this site</h2>")
    parts.append(f'    <ul class="tabs">\n{cards}    </ul>')
    return "\n".join(parts)


def render_classes(page: PageSource, entries: list[Entry]) -> str:
    parts = [heading_block(page)]

    terms: dict[str, list[Entry]] = {}
    for entry in sorted(entries, key=lambda e: (e.term_key, -e.order), reverse=True):
        terms.setdefault(entry.term, []).append(entry)

    for term, group in terms.items():
        # "— in progress" is derived, not typed into every file, so it cannot go
        # stale and does not leak into the summary table below.
        ongoing = any(e.status.lower() in ACTIVE_STATUSES for e in group)
        label = render_inline(term) + (" &mdash; in progress" if ongoing else "")
        parts.append(f"\n    <h2>{label}</h2>\n")
        parts.extend(entry.render() for entry in group)

    if entries:
        rows = []
        for entry in (e for group in terms.values() for e in group):
            note = render_inline(entry.notes[0]) if entry.notes else "&mdash;"
            rows.append(
                f"          <tr><td>{render_inline(entry.term)}</td>"
                f"<td>{render_inline(entry.course) or '&mdash;'}</td>"
                f"<td>{render_inline(entry.title)}</td><td>{note}</td></tr>"
            )
        parts.append(f"""
    <hr>

    <h2>At a glance</h2>
    <div class="table-scroll">
      <table>
        <thead>
          <tr><th scope="col">Term</th><th scope="col">Course</th><th scope="col">Topic</th><th scope="col">Notes</th></tr>
        </thead>
        <tbody>
{chr(10).join(rows)}
        </tbody>
      </table>
    </div>""")

    if page.body_html:
        parts.append("\n    <hr>\n")
        parts.append(textwrap.indent(page.body_html, "    "))
    return "\n".join(parts)


def render_research(page: PageSource, entries: list[Entry]) -> str:
    parts = [heading_block(page), ""]
    parts.extend(entry.render() for entry in sorted(entries, key=lambda e: (e.order, e.path.name)))
    if page.body_html:
        parts.append("\n    <hr>\n")
        parts.append(textwrap.indent(page.body_html, "    "))
    return "\n".join(parts)


